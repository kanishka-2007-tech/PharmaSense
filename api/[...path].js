const crypto = require("node:crypto");
const {neon} = require("@neondatabase/serverless");
const {
  hashPassword,
  publicUser,
  sessionCookie,
  validateCredentials,
  verifyPassword,
} = require("../server");

const SESSION_COOKIE = "pharmasense_session";
const MAX_BODY_BYTES = 16 * 1024;
let schemaReady;

function sendJson(response, status, value, headers = {}){
  response.writeHead(status, {
    "Content-Type": "application/json; charset=utf-8",
    "Cache-Control": "no-store",
    "X-Content-Type-Options": "nosniff",
    ...headers,
  });
  response.end(JSON.stringify(value));
}

function sendError(response, status, message, field){
  sendJson(response, status, field ? {message, field} : {message});
}

function getCookie(request, name){
  for(const cookie of (request.headers.cookie || "").split(";")){
    const separator = cookie.indexOf("=");
    if(separator < 0 || cookie.slice(0, separator).trim() !== name) continue;
    try{
      return decodeURIComponent(cookie.slice(separator + 1).trim());
    } catch(error){
      return null;
    }
  }
  return null;
}

function getBody(request){
  if(Number(request.headers["content-length"]) > MAX_BODY_BYTES){
    throw Object.assign(new Error("Request body is too large."), {status: 413});
  }
  if(request.body === undefined || request.body === null) return {};
  if(Buffer.isBuffer(request.body)) request.body = request.body.toString("utf8");
  if(typeof request.body === "string"){
    if(Buffer.byteLength(request.body, "utf8") > MAX_BODY_BYTES){
      throw Object.assign(new Error("Request body is too large."), {status: 413});
    }
    try{
      request.body = JSON.parse(request.body);
    } catch(error){
      throw Object.assign(new Error("Request body must be valid JSON."), {status: 400});
    }
  }
  if(typeof request.body !== "object" || Array.isArray(request.body)){
    throw Object.assign(new Error("Request body must be a JSON object."), {status: 400});
  }
  if(Buffer.byteLength(JSON.stringify(request.body), "utf8") > MAX_BODY_BYTES){
    throw Object.assign(new Error("Request body is too large."), {status: 413});
  }
  return request.body;
}

function getSessionLifetime(){
  const days = Number(process.env.SESSION_TTL_DAYS || 7);
  if(!Number.isInteger(days) || days < 1 || days > 365){
    throw new Error("SESSION_TTL_DAYS must be between 1 and 365.");
  }
  return days * 86400;
}

function ensureSchema(sql){
  if(!schemaReady){
    schemaReady = (async () => {
      await sql`CREATE TABLE IF NOT EXISTS users (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        salt TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        total_checks INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )`;
      await sql`CREATE TABLE IF NOT EXISTS sessions (
        id TEXT PRIMARY KEY,
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      )`;
      await sql`CREATE TABLE IF NOT EXISTS history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        meds JSONB NOT NULL,
        findings_count INTEGER NOT NULL,
        worst_severity TEXT NOT NULL,
        checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )`;
      await sql`CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions(user_id)`;
      await sql`CREATE INDEX IF NOT EXISTS history_user_checked_at_idx ON history(user_id, checked_at DESC, id DESC)`;
    })().catch(error => {
      schemaReady = null;
      throw error;
    });
  }
  return schemaReady;
}

async function findSession(sql, request){
  const id = getCookie(request, SESSION_COOKIE);
  if(!id) return null;
  const rows = await sql`
    SELECT users.id, users.name, users.email, users.total_checks
    FROM sessions
    JOIN users ON users.id = sessions.user_id
    WHERE sessions.id = ${id} AND sessions.expires_at > ${Date.now()}
    LIMIT 1
  `;
  return rows[0] || null;
}

function mapHistory(rows){
  return rows.map(row => ({
    meds: row.meds,
    findingsCount: row.findings_count,
    worstSeverity: row.worst_severity,
    at: new Date(row.checked_at).toISOString(),
  }));
}

async function handler(request, response){
  if(!process.env.DATABASE_URL){
    return sendError(response, 503, "Production database is not configured. Set DATABASE_URL to a Neon connection string.");
  }

  const sql = neon(process.env.DATABASE_URL);
  try{
    await ensureSchema(sql);
    const url = new URL(request.url, "https://pharmasense.invalid");
    const route = url.pathname;
    const method = request.method || "GET";

    if(method === "GET" && route === "/api/health"){
      await sql`SELECT 1`;
      return sendJson(response, 200, {ok: true});
    }

    if(method === "POST" && (route === "/api/auth/signup" || route === "/api/auth/login")){
      const signup = route === "/api/auth/signup";
      const credentials = validateCredentials(getBody(request), signup);
      if(credentials.error) return sendError(response, 400, credentials.error, credentials.field);

      const users = await sql`
        SELECT id, name, email, salt, password_hash, total_checks
        FROM users WHERE email = ${credentials.email} LIMIT 1
      `;
      let user = users[0];
      if(signup){
        if(user) return sendError(response, 409, "An account with this email already exists.", "email");
        const password = hashPassword(credentials.password);
        const userId = crypto.randomUUID();
        const sessionId = crypto.randomBytes(32).toString("hex");
        const ttl = getSessionLifetime();
        try{
          await sql.transaction([
            sql`INSERT INTO users (id, name, email, salt, password_hash)
              VALUES (${userId}, ${credentials.name}, ${credentials.email}, ${password.salt}, ${password.hash})`,
            sql`INSERT INTO sessions (id, user_id, expires_at)
              VALUES (${sessionId}, ${userId}, ${Date.now() + ttl * 1000})`,
          ]);
        } catch(error){
          if(error.code === "23505"){
            return sendError(response, 409, "An account with this email already exists.", "email");
          }
          throw error;
        }
        return sendJson(response, 201, {
          user: publicUser({name: credentials.name, email: credentials.email}),
        }, {"Set-Cookie": sessionCookie(sessionId, ttl)});
      }

      if(!user || !verifyPassword(credentials.password, {
        salt: user.salt,
        passwordHash: user.password_hash,
      })){
        return sendError(response, 401, "Email or password is incorrect.", "password");
      }

      const sessionId = crypto.randomBytes(32).toString("hex");
      const ttl = getSessionLifetime();
      await sql`
        INSERT INTO sessions (id, user_id, expires_at)
        VALUES (${sessionId}, ${user.id}, ${Date.now() + ttl * 1000})
      `;
      await sql`DELETE FROM sessions WHERE expires_at <= ${Date.now()}`;
      return sendJson(response, 200, {user: publicUser(user)}, {
        "Set-Cookie": sessionCookie(sessionId, ttl),
      });
    }

    if(method === "POST" && route === "/api/auth/logout"){
      const id = getCookie(request, SESSION_COOKIE);
      if(id) await sql`DELETE FROM sessions WHERE id = ${id}`;
      return sendJson(response, 200, {ok: true}, {
        "Set-Cookie": sessionCookie("", 0),
      });
    }

    if(method === "GET" && route === "/api/auth/session"){
      const user = await findSession(sql, request);
      if(!user) return sendError(response, 401, "Sign in to continue.");
      return sendJson(response, 200, {user: publicUser(user)});
    }

    if(route === "/api/history" && (method === "GET" || method === "POST")){
      const user = await findSession(sql, request);
      if(!user) return sendError(response, 401, "Sign in to continue.");
      if(method === "GET"){
        const rows = await sql`
          SELECT meds, findings_count, worst_severity, checked_at
          FROM history WHERE user_id = ${user.id}
          ORDER BY checked_at DESC, id DESC LIMIT 8
        `;
        return sendJson(response, 200, {
          items: mapHistory(rows),
          totalChecks: user.total_checks || 0,
        });
      }

      const body = getBody(request);
      if(!Array.isArray(body.meds) || body.meds.length < 2 || body.meds.length > 12
        || body.meds.some(medicine => typeof medicine !== "string" || !medicine.trim() || medicine.length > 120)){
        return sendError(response, 400, "A check must contain between 2 and 12 valid medicine names.");
      }
      if(!Number.isInteger(body.findingsCount) || body.findingsCount < 0 || body.findingsCount > 100){
        return sendError(response, 400, "The findings count is invalid.");
      }
      if(!["danger", "caution", "safe"].includes(body.worstSeverity)){
        return sendError(response, 400, "The result severity is invalid.");
      }
      await sql.transaction([
        sql`INSERT INTO history (user_id, meds, findings_count, worst_severity)
          VALUES (${user.id}, ${JSON.stringify(body.meds.map(medicine => medicine.trim()))}::jsonb,
            ${body.findingsCount}, ${body.worstSeverity})`,
        sql`UPDATE users SET total_checks = total_checks + 1 WHERE id = ${user.id}`,
        sql`DELETE FROM history WHERE id IN (
          SELECT id FROM history WHERE user_id = ${user.id}
          ORDER BY checked_at DESC, id DESC OFFSET 8
        )`,
      ]);
      const [rows, updatedUsers] = await Promise.all([
        sql`
          SELECT meds, findings_count, worst_severity, checked_at
          FROM history WHERE user_id = ${user.id}
          ORDER BY checked_at DESC, id DESC LIMIT 8
        `,
        sql`SELECT total_checks FROM users WHERE id = ${user.id} LIMIT 1`,
      ]);
      return sendJson(response, 201, {
        items: mapHistory(rows),
        totalChecks: updatedUsers[0].total_checks,
      });
    }

    return sendError(response, 404, "API route not found.");
  } catch(error){
    if(error.status){
      return sendError(response, error.status, error.message);
    }
    console.error("Production API request failed:", error);
    return sendError(response, 500, "The server could not complete the request.");
  }
}

module.exports = handler;
module.exports.default = handler;
